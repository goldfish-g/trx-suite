// Takes the menu's lettering and button prompts from TRX's own: TR1's gold
// in-game font, and the controller and keyboard icons TRX draws in its
// prompts.
//
//   node scripts/make-game-art.mjs <TRX checkout>
//
// Reads data/tr1/glyphs from the checkout (TRX, GPL-3.0) and writes
// src/ui/gameArt: font.png, controller.png, keyboard.png and sheets.ts, the
// place of every glyph and icon on them. Only glyphs drawn whole on the
// sheet are taken; letters the game composes from parts, such as accented
// ones, are left to the text font.

import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const trx = process.argv[2];
if (trx === undefined) {
    console.error('usage: node scripts/make-game-art.mjs <TRX checkout>');
    process.exit(1);
}
const dir = join(trx, 'data/tr1/glyphs');
const out = 'src/ui/gameArt';
mkdirSync(out, { recursive: true });

/** The numbers inside expand(...) and translate(...), by name. */
function modifiers(rest) {
    let extraWidth = 0;
    let dx = 0;
    let dy = 0;
    for (const [, name, params] of rest.matchAll(/(\w+)\(([^)]*)\)/g)) {
        for (const [index, part] of params.split(',').entries()) {
            const [key, value] = part.includes('=') ? part.split('=').map((s) => s.trim()) : [null, part.trim()];
            if (name === 'expand' && (key === 'w' || (key === null && index === 0))) extraWidth += Number(value);
            if (name === 'translate' && (key === 'x' || (key === null && index === 0))) dx += Number(value);
            if (name === 'translate' && (key === 'y' || (key === null && index === 1))) dy += Number(value);
        }
    }
    return { extraWidth, dx, dy };
}

// U+0041:A 0 T manual_sprite("glyphs.png", 65, 23, 17, 18, index=0) expand(-1)
const GLYPH = /^U\+([0-9A-F]{4,6}):\S*\s+0\s+T\s+manual_sprite\("glyphs\.png",\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d+)[^)]*\)(.*)$/;
const glyphs = {};
for (const file of ['mapping_basic_latin.txt', 'mapping_latin-1_supplement.txt', 'mapping_misc.txt']) {
    for (const line of readFileSync(join(dir, file), 'utf8').split('\n')) {
        const match = GLYPH.exec(line.trim());
        if (match === null) continue;
        const [, code, x, y, w, h, rest] = match;
        const { extraWidth, dx } = modifiers(rest);
        glyphs[String.fromCodePoint(parseInt(code, 16))] = [+x, +y, +w, +h, +w + extraWidth, dx];
    }
}

// "\\{controller button a}" 0 I manual_sprite("controller.png", 0, 48, 15, 15) translate(y=2, x=1)
const ICON = /^"\\\\\{(controller|keyboard) ([^}]+)\}"\s+0\s+I\s+manual_sprite\("(\w+)\.png",\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d+)\)(.*)$/;
const WANTED = {
    controller: ['button a', 'button b', 'button x', 'button y', 'button cross', 'button circle', 'button square', 'button triangle',
        'dpad up', 'dpad down', 'dpad left', 'dpad right', 'bumper left', 'bumper right', 'button l1', 'button r1',
        'button start', 'button back', 'button options', 'button share'],
    keyboard: ['return', 'escape', 'e', 'f', 'm', 'q', 'r', 'v', 'left', 'right', 'up', 'down'],
};
const icons = {};
for (const file of ['mapping_controller.txt', 'mapping_keyboard.txt']) {
    for (const line of readFileSync(join(dir, file), 'utf8').split('\n')) {
        const match = ICON.exec(line.trim());
        if (match === null) continue;
        const [, kind, name, sheet, x, y, w, h] = match;
        if (!WANTED[kind].includes(name)) continue;
        icons[`${kind} ${name}`] = [sheet, +x, +y, +w, +h];
    }
}
for (const [kind, names] of Object.entries(WANTED)) {
    for (const name of names) if (icons[`${kind} ${name}`] === undefined) throw new Error(`no ${kind} ${name} in TRX's mapping`);
}

const glyphLines = Object.entries(glyphs).map(([char, m]) => `    ${JSON.stringify(char)}: [${m.join(', ')}],`);
const iconLines = Object.entries(icons).map(([name, [sheet, ...m]]) => `    ${JSON.stringify(name)}: [${JSON.stringify(sheet)}, ${m.join(', ')}],`);
writeFileSync(
    join(out, 'sheets.ts'),
    `// Generated by scripts/make-game-art.mjs from TRX's data/tr1/glyphs (GPL-3.0).

/** The height of a line of the font, in the sheet's pixels. */
export const LINE_HEIGHT = 18;
/** The gap TRX leaves between letters, and the width of its space. */
export const LETTER_SPACING = 0.5;
export const WORD_SPACING = 6;

/** Each glyph: x, y, width and height on font.png, how far the pen moves past it, and how far right of the pen it is drawn. */
export const GLYPHS: Record<string, readonly [number, number, number, number, number, number]> = {
${glyphLines.join('\n')}
};

/** Each icon: its sheet, and x, y, width and height on it. */
export const ICONS = {
${iconLines.join('\n')}
} as const satisfies Record<string, readonly ['controller' | 'keyboard', number, number, number, number]>;

export type IconName = keyof typeof ICONS;
`,
);
copyFileSync(join(dir, 'glyphs.png'), join(out, 'font.png'));
copyFileSync(join(dir, 'controller.png'), join(out, 'controller.png'));
copyFileSync(join(dir, 'keyboard.png'), join(out, 'keyboard.png'));
console.log(`${Object.keys(glyphs).length} glyphs, ${Object.keys(icons).length} icons`);
